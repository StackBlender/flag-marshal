/**
 * Regenerates THIRD_PARTY_NOTICES.md from the installed runtime dependencies.
 *
 * Every runtime dependency is MIT or ISC, and both require the copyright notice
 * and licence text to travel with redistributed copies. Shipping a package
 * built on them without attribution is a licence breach, not a formality.
 *
 * Only *runtime* dependencies are listed. Development dependencies are not
 * redistributed, so they carry no obligation here.
 *
 * Usage: node scripts/third-party-notices.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(root, 'THIRD_PARTY_NOTICES.md');

const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const names = Object.keys(pkg.dependencies ?? {}).sort();

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license'];

async function licenseTextFor(name) {
  const base = resolve(root, 'node_modules', name);
  for (const candidate of LICENSE_FILES) {
    try {
      return (await readFile(resolve(base, candidate), 'utf8')).trim();
    } catch {
      continue;
    }
  }
  return undefined;
}

const sections = [];
for (const name of names) {
  // Read from node_modules directly. Some packages intentionally do not export
  // package.json, so require("name/package.json") is not a reliable metadata API.
  const meta = JSON.parse(
    await readFile(resolve(root, 'node_modules', name, 'package.json'), 'utf8'),
  );
  const text = await licenseTextFor(name);
  const source = meta.repository?.url
    ? `Source: ${String(meta.repository.url)
        .replace(/^git\+/, '')
        .replace(/\.git$/, '')}`
    : undefined;
  sections.push(
    [
      `## ${name}@${meta.version}`,
      '',
      `License: ${meta.license ?? 'see below'}`,
      ...(source === undefined ? [] : [source]),
      '',
      '```text',
      text ??
        `No licence file was bundled with ${name}. Declared license: ${meta.license ?? 'unknown'}.`,
      '```',
    ].join('\n'),
  );
}

const document = [
  '# Third-party notices',
  '',
  `StackBlender Flag Marshal redistributes the runtime dependencies below. Each is`,
  'reproduced with its copyright notice and licence text as those licences require.',
  '',
  'Generated by `node scripts/third-party-notices.mjs`. Regenerate after changing a',
  'runtime dependency; `npm run check` fails if this file is stale.',
  '',
  ...sections,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (current !== document) {
    console.error('THIRD_PARTY_NOTICES.md is stale. Run: npm run notices');
    process.exit(1);
  }
  console.log('Third-party notices are up to date.');
} else {
  await writeFile(OUTPUT, document, 'utf8');
  console.log(`Wrote ${OUTPUT} for ${names.length} runtime dependencies.`);
}
